#!/bin/sh
# Desktop regression suite for the browser engine and UI.
#
# Starts the fixture server (tests/fixtures/server.py) on a free local port, drives the
# desktop build (kb-desktop) through scripted commands, and checks the log for the
# expected results. Exit status is 0 only if every scenario passes.
#
#   scripts/desktop-regression.sh [--network]
#
# --network also runs scenarios against live sites (Hacker News, Wikipedia). Those depend
# on the internet and on the sites' markup, so they are opt-in.
#
# Environment: KB_BIN (default target/release/kb-desktop), KB_PORT (default 8780),
# KB_TEST_OUT (default: a temporary folder; frames and logs are kept there).
set -u

ROOT=$(cd "$(dirname "$0")/.." && pwd)
BIN=${KB_BIN:-$ROOT/target/release/kb-desktop}
PORT=${KB_PORT:-8780}
FIXTURES=$ROOT/tests/fixtures
OUT=${KB_TEST_OUT:-$(mktemp -d)}
# Artifacts are kept in the repository: one folder per scenario with its script, driver log,
# final screen and named screenshots, plus INDEX.md. Set KB_ARTIFACTS to write elsewhere.
ARTIFACTS=${KB_ARTIFACTS:-$ROOT/artifacts/desktop}
FONTS=$(ls "$ROOT"/assets/fonts/*.ttf | paste -sd, -)
BASE=http://127.0.0.1:$PORT
NETWORK=0
[ "${1:-}" = "--network" ] && NETWORK=1
mkdir -p "$OUT" "$ARTIFACTS" || exit 2
# Clear the previous run's scenario folders (only the generated ones) and index.
rm -rf "$ARTIFACTS"/*/ "$ARTIFACTS/INDEX.md"
: >"$OUT/results.txt"

[ -x "$BIN" ] || { echo "missing binary: $BIN (build with: cargo build --release -p kb-desktop)"; exit 2; }

python3 "$FIXTURES/server.py" "$PORT" >"$OUT/server.log" 2>&1 &
SERVER=$!
trap 'kill $SERVER 2>/dev/null' EXIT INT TERM
sleep 1

pass=0
fail=0
failed=""

# run NAME SCRIPT EXPECT...  - runs the script, then checks each EXPECT substring is in the log.
# seed_bookmarks DIR COUNT - writes COUNT bookmarks ("Bookmark 0" .. "Bookmark N-1") to DIR.
# Each points at a fixture page with a query string, so opening one loads the plain fixture.
seed_bookmarks() {
    : >"$1/bookmarks.tsv"
    i=0
    while [ "$i" -lt "$2" ]; do
        printf '%s/plain.html?b=%d\tBookmark %d\n' "$BASE" "$i" "$i" >>"$1/bookmarks.tsv"
        i=$((i + 1))
    done
}

run() {
    name=$1
    script=$2
    shift 2
    dir="$ARTIFACTS/$name"
    mkdir -p "$dir"
    printf '%s\n' "$script" >"$dir/script.txt"
    data=$(mktemp -d)
    # SEED=n (set by the caller) starts the scenario with n bookmarks: a long list.
    if [ -n "${SEED:-}" ]; then
        seed_bookmarks "$data" "$SEED"
    fi
    printf '%s\n' "$script" | KB_FONTS="$FONTS" KB_DATA="$data" KB_OUT="$dir/final.png" KB_SHOTS="$dir" \
        timeout 300 "$BIN" >"$dir/log.txt" 2>&1
    rc=$?
    ok=1
    if [ $rc -ne 0 ]; then
        ok=0
        echo "  exit status $rc"
    fi
    for want in "$@"; do
        if ! grep -qF -- "$want" "$dir/log.txt"; then
            ok=0
            echo "  missing in log: $want"
        fi
    done
    if [ $ok -eq 1 ]; then
        pass=$((pass + 1))
        echo "PASS $name"
        echo "$name PASS" >>"$OUT/results.txt"
    else
        fail=$((fail + 1))
        failed="$failed $name"
        echo "FAIL $name  (log: $dir/log.txt)"
        echo "$name FAIL" >>"$OUT/results.txt"
    fi
}

# write_index - INDEX.md: one row per scenario with its result, final screen and named shots.
write_index() {
    {
        echo "# Desktop test artifacts"
        echo
        echo "Generated by \`scripts/desktop-regression.sh\` on $(date '+%Y-%m-%d %H:%M'): passed $pass, failed $fail."
        echo
        echo "Each scenario folder holds \`script.txt\` (the driver commands), \`log.txt\` (the driver's log),"
        echo "\`final.png\` (the screen at the end) and any named shots taken with \`shot\`."
        echo
        echo "| Scenario | Result | Final screen | Named shots |"
        echo "|---|---|---|---|"
        while read -r name status; do
            shots=$(cd "$ARTIFACTS/$name" && ls *.png 2>/dev/null | grep -v '^final\.png$' | sed 's/\.png$//' |
                while read -r s; do printf '[%s](%s/%s.png) ' "$s" "$name" "$s"; done)
            echo "| $name | $status | [final]($name/final.png) | ${shots:-—} |"
        done <"$OUT/results.txt"
    } >"$ARTIFACTS/INDEX.md"
}

