#!/bin/sh
# Full test pipeline. Runs every check and keeps the evidence in the repository:
#
#   artifacts/REPORT.md              summary: each step, its result, and links to its logs
#   artifacts/build.log              workspace build (desktop)
#   artifacts/unit/unit-tests.log    unit tests of every crate
#   artifacts/desktop/INDEX.md       desktop regression: one folder per scenario with
#                                    script.txt, log.txt, final.png and named screenshots
#   artifacts/launcher/launcher-stub-test.log
#   artifacts/device/arm-build.log   cross-build for the Kindle (armv7), with the binary size
#                                    and whether it matches the copy on the mounted Kindle
#
# Usage: scripts/test-all.sh [--network]
#   --network  also run the live-site scenarios (opt-in; needs the internet)
#
# Exit status is 0 only if every required step passes. The ARM build is skipped (not failed)
# when cargo-zigbuild is not installed; the step is reported as SKIP.
set -u

ROOT=$(cd "$(dirname "$0")/.." && pwd)
ART=$ROOT/artifacts
NETWORK_FLAG=""
[ "${1:-}" = "--network" ] && NETWORK_FLAG="--network"
export PATH="$HOME/.cargo/bin:/opt/homebrew/bin:$PATH"
if [ -x "$HOME/.rustup/toolchains/stable-aarch64-apple-darwin/bin/cargo" ]; then
    export PATH="$HOME/.rustup/toolchains/stable-aarch64-apple-darwin/bin:$PATH"
fi

mkdir -p "$ART/unit" "$ART/launcher" "$ART/device"
rows=""
failed=0

# step NAME LOG-PATH COMMAND... - run a step, keep its output in LOG-PATH, record the result.
step() {
    name=$1
    log=$2
    shift 2
    if "$@" >"$log" 2>&1; then
        result=PASS
    else
        result=FAIL
        failed=$((failed + 1))
    fi
    rows="$rows| $name | $result | ${log#$ROOT/} |
"
    echo "$result  $name"
}

cd "$ROOT" || exit 2
echo "== test pipeline: $ROOT"
step "build (desktop, release)" "$ART/build.log" cargo build --release --workspace
step "unit tests (all crates)" "$ART/unit/unit-tests.log" cargo test --release --workspace
step "desktop regression (with screenshots)" "$ART/desktop-regression.log" \
    sh scripts/desktop-regression.sh $NETWORK_FLAG
step "launcher stub tests" "$ART/launcher/launcher-stub-test.log" sh scripts/launcher-stub-test.sh

# Device build: optional, needs cargo-zigbuild and the ARM target.
arm_log="$ART/device/arm-build.log"
if command -v cargo-zigbuild >/dev/null 2>&1 || cargo zigbuild --help >/dev/null 2>&1; then
    step "cross-build (Kindle armv7)" "$arm_log" \
        cargo zigbuild --release -p kb-kindle --target armv7-unknown-linux-musleabihf
    if [ -f "$ROOT/target/armv7-unknown-linux-musleabihf/release/kb-kindle" ]; then
        bin="$ROOT/target/armv7-unknown-linux-musleabihf/release/kb-kindle"
        {
            echo "binary: $bin"
            echo "size: $(wc -c <"$bin") bytes"
            if [ -f /Volumes/Kindle/browser/kb-kindle ]; then
                if cmp -s "$bin" /Volumes/Kindle/browser/kb-kindle; then
                    echo "device copy: matches this build"
                else
                    echo "device copy: differs from this build (run deploy/install.sh)"
                fi
            else
                echo "device copy: Kindle not mounted"
            fi
        } >>"$arm_log"
    fi
else
    rows="$rows| cross-build (Kindle armv7) | SKIP | cargo-zigbuild not installed |
"
    echo "SKIP  cross-build (Kindle armv7): cargo-zigbuild not installed"
fi

{
    echo "# Test report"
    echo
    echo "Generated by \`scripts/test-all.sh\` on $(date '+%Y-%m-%d %H:%M')."
    echo
    echo "| Step | Result | Evidence |"
    echo "|---|---|---|"
    printf '%s' "$rows"
    echo
    echo "Desktop screenshots, one folder per scenario: [INDEX.md](desktop/INDEX.md)."
    echo
    if [ "$failed" -eq 0 ]; then
        echo "**Result: all required steps passed.**"
    else
        echo "**Result: $failed step(s) failed; see the logs above.**"
    fi
} >"$ART/REPORT.md"

echo
echo "report: artifacts/REPORT.md"
[ "$failed" -eq 0 ] || exit 1
exit 0
